-- VidNotes AI cloud schema for Supabase Postgres.
--
-- Run it once in the Supabase Dashboard: SQL Editor > New query > paste > Run.
-- It is safe to run again: it only creates what is missing and refreshes the
-- security policies. It never deletes data.
--
-- Every table holds data of exactly one user (user_id = Supabase Auth user id)
-- and Row Level Security only lets a signed-in user read or change their own
-- rows. Composite foreign keys also stop a row from pointing at another
-- user's video.

-- ---------------------------------------------------------------- tables

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email varchar(320),
  full_name varchar(200),
  avatar_url varchar(1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_preferences (
  user_id uuid primary key references auth.users (id) on delete cascade,
  theme varchar(10) not null default 'dark' check (theme in ('dark', 'light')),
  default_language varchar(20) not null default 'en' check (default_language in ('en', 'hinglish')),
  default_quiz_count integer not null default 10 check (default_quiz_count between 5 and 20),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Processed videos: the user's video history.
create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  youtube_id varchar(11) not null,
  url varchar(200) not null,
  title varchar(300) not null default 'Untitled video',
  channel_name varchar(200),
  thumbnail_url varchar(300),
  duration_seconds integer,
  transcript_language varchar(20),
  quiz_count integer not null default 10,
  status varchar(20) not null default 'processing',
  progress integer not null default 0,
  progress_message varchar(200) not null default 'Queued',
  error_message text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, youtube_id),
  -- Lets child tables reference (video, owner) pairs.
  unique (id, user_id)
);

-- Summary, study notes and timestamps, one row per video and language.
create table if not exists public.study_materials (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  video_id bigint not null,
  language varchar(20) not null,
  summary jsonb not null,
  notes jsonb not null,
  timestamps jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (video_id, language),
  foreign key (video_id, user_id) references public.videos (id, user_id) on delete cascade
);

create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  video_id bigint not null,
  language varchar(20) not null,
  position integer not null,
  question text not null,
  options jsonb not null,
  correct_index integer not null,
  explanation text not null,
  foreign key (video_id, user_id) references public.videos (id, user_id) on delete cascade
);

create table if not exists public.qa_pairs (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  video_id bigint not null,
  language varchar(20) not null,
  position integer not null,
  question text not null,
  answer text not null,
  foreign key (video_id, user_id) references public.videos (id, user_id) on delete cascade
);

-- Finished quiz attempts.
create table if not exists public.quiz_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  video_id bigint not null,
  language varchar(20) not null,
  score integer not null check (score >= 0),
  total integer not null check (total > 0 and score <= total),
  answers jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (video_id, user_id) references public.videos (id, user_id) on delete cascade
);

create table if not exists public.todos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  title varchar(200) not null check (length(trim(title)) > 0),
  is_done boolean not null default false,
  due_date date,
  video_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Deleting a video keeps the task and only clears the link.
  foreign key (video_id, user_id) references public.videos (id, user_id) on delete set null (video_id)
);

create index if not exists videos_user_id_idx on public.videos (user_id);
create index if not exists study_materials_user_video_idx on public.study_materials (user_id, video_id);
create index if not exists quiz_questions_user_video_idx on public.quiz_questions (user_id, video_id);
create index if not exists qa_pairs_user_video_idx on public.qa_pairs (user_id, video_id);
create index if not exists quiz_results_user_video_idx on public.quiz_results (user_id, video_id);
create index if not exists todos_user_id_idx on public.todos (user_id);
create index if not exists todos_video_id_idx on public.todos (video_id);

-- ------------------------------------------------------ row level security

alter table public.profiles enable row level security;
alter table public.user_preferences enable row level security;
alter table public.videos enable row level security;
alter table public.study_materials enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.qa_pairs enable row level security;
alter table public.quiz_results enable row level security;
alter table public.todos enable row level security;

-- One set of owner-only policies per table. (select auth.uid()) is evaluated
-- once per query, as Supabase recommends for performance.
do $$
declare
  owned record;
begin
  for owned in
    select * from (values
      ('profiles', 'id'),
      ('user_preferences', 'user_id'),
      ('videos', 'user_id'),
      ('study_materials', 'user_id'),
      ('quiz_questions', 'user_id'),
      ('qa_pairs', 'user_id'),
      ('quiz_results', 'user_id'),
      ('todos', 'user_id')
    ) as t (table_name, owner_column)
  loop
    execute format('drop policy if exists "Owners can read" on public.%I', owned.table_name);
    execute format('drop policy if exists "Owners can insert" on public.%I', owned.table_name);
    execute format('drop policy if exists "Owners can update" on public.%I', owned.table_name);
    execute format('drop policy if exists "Owners can delete" on public.%I', owned.table_name);

    execute format(
      'create policy "Owners can read" on public.%I for select to authenticated using ((select auth.uid()) = %I)',
      owned.table_name, owned.owner_column);
    execute format(
      'create policy "Owners can insert" on public.%I for insert to authenticated with check ((select auth.uid()) = %I)',
      owned.table_name, owned.owner_column);
    execute format(
      'create policy "Owners can update" on public.%I for update to authenticated '
      'using ((select auth.uid()) = %I) with check ((select auth.uid()) = %I)',
      owned.table_name, owned.owner_column, owned.owner_column);
    execute format(
      'create policy "Owners can delete" on public.%I for delete to authenticated using ((select auth.uid()) = %I)',
      owned.table_name, owned.owner_column);

    -- Signed-out visitors (the anon role) get no access at all.
    execute format('revoke all on table public.%I from anon', owned.table_name);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', owned.table_name);
  end loop;
end
$$;

grant usage, select on all sequences in schema public to authenticated;
